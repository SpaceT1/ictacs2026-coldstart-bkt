# ---------------------------------------------------------------- S1
w('## S1. Experiment 1 - prediction on ASSISTments 2009-2010 (48 skills, 257,749 test responses)\n')
w('Pooled metrics over all test predictions with 95% CIs from a learner-level cluster bootstrap '
  '(1,000 resamples of learners). AUC/skill = mean of the 48 per-skill AUCs. '
  'Pilot rows: mean over three independent pilot draws per skill and fold (range over draws in brackets).\n')
w('| Model | Pooled AUC [95% CI] | AUC/skill | RMSE [95% CI] |')
w('|---|---|---|---|')
def m(name, key, pskey):
    e = S1[key]
    a = f"{e['auc']:.3f}" + (f" [{e['auc_ci'][0]:.3f}, {e['auc_ci'][1]:.3f}]" if 'auc_ci' in e else '')
    ps = PS[pskey].mean() if pskey in PS else np.nan
    w(f"| {name} | {a} | {ps:.3f} | {e['rmse']:.3f} [{e['rmse_ci'][0]:.3f}, {e['rmse_ci'][1]:.3f}] |")
m('Constant (training-fold proportion correct)', 'Constant', 'Constant_auc')
m('Learner running mean, (s + k m)/(n + k), k tuned on training fold', 'Learner mean', 'Learner mean_auc')
m('PFA (logistic regression on earlier successes/failures)', 'PFA', 'PFA_auc')
m('BKT, canonical (0.10 / 0.25 / 0.20 / 0.10)', 'Canonical', 'Canonical_auc')
m('BKT, all four parameters fitted on full training fold', 'Fitted-all', 'Fitted-all_auc')
m('BKT, prior fixed at 0.10, learn/guess/slip fitted (full fold)', 'Full-noprior', 'Full-noprior_auc')
m('BKT, only prior fitted, learn/guess/slip canonical (full fold)', 'Full-prioronly', 'Full-prioronly_auc')
d = S1['diff_fit_minus_canon_auc']
w(f"\nPooled AUC difference fitted - canonical: {d['est']:.3f} [{d['ci'][0]:.3f}, {d['ci'][1]:.3f}].\n")
p = S1['perskill']
w('Per-skill paired comparisons (mean difference, bootstrap 95% CI over skills, Wilcoxon signed-rank):\n')
for k, lab in (('fit_vs_canon_auc', 'AUC, fitted - canonical'), ('fit_vs_canon_rmse', 'RMSE, canonical - fitted'),
               ('pfa_vs_fit_auc', 'AUC, PFA - fitted BKT'), ('lmean_vs_fit_auc', 'AUC, running mean - fitted BKT'),
               ('pfa_vs_canon_auc', 'AUC, PFA - canonical BKT')):
    e = p[k]
    w(f"- {lab}: {e['mean_diff']:.3f} [{e['ci'][0]:.3f}, {e['ci'][1]:.3f}], positive on {e['n_pos']}/48 skills, p = {e['p_wilcoxon']:.2g}")
